/** 先頭の --- で囲まれた見出し（Skill の名前と説明）を除いた本文 */
export function skillBody(text: string): string {
  const m = /^---\r?\n[\s\S]*?\r?\n---\r?\n?/.exec(text);
  return (m ? text.slice(m[0].length) : text).trim();
}

export const JEWELER_GUIDES = skillBody(skillText);

