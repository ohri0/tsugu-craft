/** 温度の幅を画面の言葉に（同じ値なら 1 つ） */
export function rangeC(r: readonly [number, number] | undefined): string {
  if (!r) return "鋳造所・職人の値";
  return r[0] === r[1] ? `約 ${r[0]} ℃` : `${r[0]}〜${r[1]} ℃`;
}

/** 文の中に出てくる、説明のあることば（文に出てくる順、重なりなし） */
export function termsIn(text: string): Term[] {
  const hits: { term: Term; at: number }[] = [];
  for (const term of TERMS) {
    const at = text.indexOf(term.word);
    if (at >= 0) hits.push({ term, at });
  }
  // 長いことばの中に入っている短いことば（「V 字の爪」の中の「爪」など）は、長い方がもう出ていれば省く
  const kept = hits.filter(
    (h) =>
      !hits.some(
        (o) =>
          o !== h &&
          o.term.word.length > h.term.word.length &&
          o.term.word.includes(h.term.word) &&
          !textHasOutside(text, h.term.word, o.term.word),
      ),
  );
  return kept.sort((a, b) => a.at - b.at).map((h) => h.term);
}

/** short が long の外にも出てくるか */
function textHasOutside(text: string, short: string, long: string): boolean {
  return text.split(long).some((part) => part.includes(short));
}
